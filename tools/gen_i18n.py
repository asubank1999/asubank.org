"""App translations (Arabic, Spanish) for the iOS and Android apps.

  python tools/gen_i18n.py --extract   lists English UI strings in the app sources that i18n/strings.json lacks
  python tools/gen_i18n.py             writes the app files from i18n/strings.json:
      ios/ASUBank/{en,ar,es}.lproj/Localizable.strings
      android/app/src/main/assets/i18n.json

i18n/strings.json is {"English text": {"ar": "...", "es": "..."}}. A missing language falls back to English.
iOS translates SwiftUI Text("literal") by itself; both apps use L()/tr() for text built in code, and the Android
Text() in Lang.kt translates any string that is a key here.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'i18n', 'strings.json')

# English UI text inside the common SwiftUI / Compose calls
CALLS = r'(?:Text|Label|Button|Toggle|TextField|SecureField|Section|navigationTitle|Stepper|Picker|Badge|ListRow|Screen|EmptyState|SwitchRow|L|tr|' \
        r'header|footer|title|subtitle|placeholder|label|Field|SignInPrompt|row|info|choice|big)'
LIT = re.compile(CALLS + r'\s*(?:\(|=)\s*(?:text:\s*)?"((?:[^"\\]|\\.)*)"')
# second string arguments: ListRow("a", "b"), Field(x, y, "label"), EmptyState(icon, "a", "b"), SignInPrompt("a", "b")
LIT2 = re.compile(r'(?:ListRow|EmptyState|SignInPrompt|SwitchRow|Field|row|info)\s*\([^()\n]*?,\s*"((?:[^"\\]|\\.)*)"')
PAIR = re.compile(r'"((?:[^"\\]|\\.)*)"\s+to\s+"((?:[^"\\]|\\.)*)"')  # Kotlin "key" to "Label"
TUPLE = re.compile(r'\(\s*"[a-z]\w*"\s*,\s*"((?:[^"\\]|\\.)*)"')  # Swift ("key", "Label", ...)


def looks_like_ui(s):
    if not s or len(s) < 2 or s.startswith(('http', '/', '#', 'ab.', 'org.', 'image/', 'text/')):
        return False
    if '\\(' in s or '${' in s or re.fullmatch(r'[\w.\-]+', s) and s[0].islower():
        return False
    if not re.search(r'[A-Za-z]{2}', s):
        return False
    return True


def extract():
    have = json.load(open(SRC, encoding='utf-8')) if os.path.exists(SRC) else {}
    found = {}
    dirs = [os.path.join(ROOT, 'ios', 'ASUBank'), os.path.join(ROOT, 'android', 'app', 'src', 'main', 'java', 'org', 'asubank', 'app')]
    for d in dirs:
        for f in sorted(os.listdir(d)):
            if not f.endswith(('.swift', '.kt')):
                continue
            text = open(os.path.join(d, f), encoding='utf-8').read()
            for rx in (LIT, LIT2):
                for m in rx.finditer(text):
                    s = m.group(1)
                    if looks_like_ui(s):
                        found.setdefault(s, f)
            for m in PAIR.finditer(text):
                if looks_like_ui(m.group(2)):
                    found.setdefault(m.group(2), f)
            for m in TUPLE.finditer(text):
                if looks_like_ui(m.group(1)):
                    found.setdefault(m.group(1), f)
    missing = {k: v for k, v in found.items() if k not in have}
    json.dump(sorted(missing), sys.stdout, ensure_ascii=False, indent=0)
    print('\n%d strings, %d missing' % (len(found), len(missing)), file=sys.stderr)


def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def write():
    data = json.load(open(SRC, encoding='utf-8'))
    for lang in ('en', 'ar', 'es'):
        d = os.path.join(ROOT, 'ios', 'ASUBank', lang + '.lproj')
        os.makedirs(d, exist_ok=True)
        entries = {}
        for k in sorted(data):
            v = k if lang == 'en' else data[k].get(lang) or k
            ik = k.replace('%s', '%@')
            iv = v.replace('%s', '%@')
            entries.setdefault(ik, iv)
            # SwiftUI looks up Text("… \(int) …") as %lld
            if '%d' in k:
                entries.setdefault(ik.replace('%d', '%lld'), iv.replace('%d', '%lld'))
                if k.count('%d') == 1:
                    entries.setdefault(ik.replace('%d', '%@'), iv.replace('%d', '%@'))
        lines = ['/* Generated by tools/gen_i18n.py from i18n/strings.json. Edit that file instead. */']
        lines += ['"%s" = "%s";' % (esc(k), esc(v)) for k, v in entries.items()]
        open(os.path.join(d, 'Localizable.strings'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    out = {lang: {k: v[lang] for k, v in data.items() if v.get(lang)} for lang in ('ar', 'es')}
    a = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'assets')
    os.makedirs(a, exist_ok=True)
    json.dump(out, open(os.path.join(a, 'i18n.json'), 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, separators=(',', ':'))
    print('wrote %d strings' % len(data))


if __name__ == '__main__':
    extract() if '--extract' in sys.argv else write()
